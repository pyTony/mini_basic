    def _announce_bbc_sdl_keyword_hints(
        self,
        parsed_lines: List[Tuple[int, str, int]],
    ) -> None:
        """Portability notes for BBC BASIC for SDL 2.0 keyword spelling.

        mini_basic accepts WEND, ENDWHILE, END WHILE, BREAK, etc. These notes
        only matter if you will also run the program under BBCSDL.
        """
        if self.config.dialect != 'bbc':
            return
        legacy: List[str] = []
        for line_num, statement, _ in parsed_lines:
            upper = statement.upper()
            if re.search(r'\bEND\s+IF\b', upper):
                legacy.append(
                    f'line {line_num}: for BBCSDL write ENDIF '
                    f'(not "END IF"); mini_basic accepts both'
                )
            if re.search(r'\bEND\s+WHILE\b', upper):
                legacy.append(
                    f'line {line_num}: for BBCSDL write ENDWHILE '
                    f'(not "END WHILE"); mini_basic accepts both'
                )
            if re.search(r'\bWEND\b', upper) and 'ENDWHILE' not in upper:
                legacy.append(
                    f'line {line_num}: for BBCSDL prefer ENDWHILE '
                    f'(SDL rejects WEND); mini_basic accepts WEND and ENDWHILE'
                )
            if re.search(r'\bBREAK\b', upper):
                legacy.append(
                    f'line {line_num}: for BBCSDL use EXIT FOR / EXIT WHILE / '
                    f'EXIT REPEAT (not BREAK); mini_basic accepts BREAK'
                )
        if not legacy:
            return
        print(
            'Note: BBCSDL portability (this program still runs here as written):'
        )
        for hint in legacy[:4]:
            print(f'  {hint}')
        if len(legacy) > 4:
            print(f'  …and {len(legacy) - 4} more')

    def _refresh_defint_bare_subst_patterns(self) -> None:
        """DEFINT makes bare A..Z names alias the same integer as A%..Z%."""
        id_flags = self._identifier_re_flags()
        existing = {
            (pattern.pattern, var)
            for pattern, var in self._var_subst_int_entries
        }
        for letter, kind in self.default_var_types.items():
            if kind != 'int' or len(letter) != 1:
                continue
            pattern = re.compile(
                r'\b' + re.escape(letter) + r'\b(?![%$!#])',
                id_flags,
            )
            key = (pattern.pattern, letter)
            if key not in existing:
                self._var_subst_int_entries.append((pattern, letter))
        self._var_subst_int_entries.sort(key=lambda item: len(item[1]), reverse=True)

    @staticmethod
    def _is_rem_only_statement(rest: str) -> bool:
        return bool(re.match(r'^REM(?:\s|$)', rest.strip(), re.IGNORECASE))

    def _unknown_statement_message(self, line: str) -> str:
        keyword = self._statement_keyword(line)
        if keyword in self._UNIMPLEMENTED_COMMANDS:
            detail = self._UNIMPLEMENTED_COMMANDS[keyword]
            return f'? Unimplemented: {detail}'
        # Crunched BBC forms (PRINTTAB, DEFPROC…) only expand in --dialect bbc.
        if (
            getattr(self.config, 'dialect', None) != 'bbc'
            and re.search(
                r'\b(PRINTTAB|PRINTSPC|PRINTCHR\$|DEFPROC|DEFPROC\w|'
                r'ENDWHILE|ENDCASE|ENDIF|PROCPUT|PROC\w)\b',
                line,
                re.IGNORECASE,
            )
        ):
            hint = keyword or line.strip().split()[0] if line.strip() else 'statement'
            return (
                f'? Unknown statement: {hint}  '
                f'(BBC-style glued form? try: --dialect bbc)'
            )
        if keyword:
            return f'? Unknown statement: {keyword}'
        preview = line.strip()
        if len(preview) > 48:
            preview = preview[:45] + '...'
        return f'? Syntax error: `{preview}`'

    def _is_structured_if(self, rest: str) -> bool:
        """True when rest is ``cond THEN`` with nothing after THEN (block IF / ENDIF)."""
        text = rest.strip()
        then_at = self._find_then_keyword(text)
        if then_at is None:
            return False
        return not text[then_at + 4:].strip()

    def _split_if_else_parts(self, rest: str) -> Tuple[str, Optional[str]]:
        parts: List[str] = []
        current: List[str] = []
        in_string = False
        depth = 0
        index = 0
        text = rest.strip()
        while index < len(text):
            ch = text[index]
            if ch == '"':
                in_string = not in_string
                current.append(ch)
                index += 1
                continue
            if not in_string and depth == 0 and text[index:index + 4].upper() == 'ELSE':
                before = text[max(0, index - 1):index]
                after = text[index + 4:index + 5]
                if (not before or not before[-1].isalnum()) and (not after or not after.isalnum()):
                    parts.append(''.join(current).strip())
                    current = []
                    index += 4
                    continue
            if ch == '(' and not in_string:
                depth += 1
            elif ch == ')' and not in_string:
                depth -= 1
            current.append(ch)
            index += 1
        parts.append(''.join(current).strip())
        if len(parts) == 1:
            return parts[0], None
        if len(parts) == 2:
            return parts[0], parts[1]
        raise ValueError('invalid IF syntax')

    def _extract_branch_condition(self, rest: str) -> str:
        text = rest.strip()
        then_at = self._find_then_keyword(text)
        if then_at is None or text[then_at + 4:].strip():
            raise ValueError('expected THEN at end of line')
        cond = text[:then_at].strip()
        if not cond:
            raise ValueError('expected THEN at end of line')
        return cond

    def _begin_if_branch(self, layout: IfBlockLayout, branch_index: int, condition: Optional[str]) -> Optional[int]:
        if not self.if_stack:
            self._runtime_error('? IF error', self._active_line_num or 0, 0)
            return None
        frame = self.if_stack[-1]
        if frame.branch_taken:
            return layout.endif_line
        if condition is None:
            frame.branch_taken = True
            return None
        if self._eval_condition(condition):
            frame.branch_taken = True
            return None
        return self._next_if_branch_line(layout, branch_index)

    def _is_case_of_header(self, rest: str) -> bool:
        return bool(re.match(r'^.+?\s+OF\s*$', rest.strip(), re.IGNORECASE))

    def _split_when_spec_and_inline(
        self,
        rest: str,
        *,
        case_true: bool = False,
    ) -> Tuple[str, Optional[str]]:
        text = rest.strip()
        if not text:
            raise ValueError('empty WHEN')
        if case_true:
            # Prefer BBC ``WHEN cond : body`` (colon at depth 0), but if the
            # text before the first colon already contains an assignment
            # (``WHEN R%<=0.5 A=1: B=2``), body starts at that assign — not at
            # the colon (which only separates multi-statement body).
            head, tail = self._split_first_at_depth(text, ':')
            assign_in_head = re.search(
                r'\s+([A-Za-z][A-Za-z0-9_%$]*)\s*=',
                head if head else text,
            )
            if assign_in_head:
                spec = text[: assign_in_head.start()].strip().rstrip(':').strip()
                inline = text[assign_in_head.start() :].strip()
                if spec:
                    return spec, inline or None
            if tail:
                return head, tail
            assign = re.search(
                r'\s+([A-Za-z][A-Za-z0-9_%$]*)\s*=',
                text,
            )
            if assign:
                spec = text[: assign.start()].strip().rstrip(':').strip()
                inline = text[assign.start() :].strip()
                if spec:
                    return spec, inline or None
            return text, None
        spec, inline = self._split_first_at_depth(text, ':')
        if not spec:
            raise ValueError('empty WHEN')
        return spec, inline or None

    def _select_case_branch(self, layout: CaseBlockLayout) -> Optional[int]:
        case_true = bool(
            layout.case_expr
            and re.fullmatch(r'TRUE', layout.case_expr.strip(), re.IGNORECASE),
        )
        if case_true:
            case_value: object = True
        else:
            try:
                case_value = self._eval_numeric(layout.case_expr or '0')
            except Exception as exc:
                self._emit_error(self._error_message('? CASE error', exc))
                return layout.otherwise_index
        for index, spec in enumerate(layout.branch_specs):
            if layout.otherwise_index is not None and index == layout.otherwise_index:
                continue
            if self._match_when_spec(case_value, spec, case_true=case_true):
                return index
        return layout.otherwise_index

    def _begin_case_branch(
        self,
        layout: CaseBlockLayout,
        branch_index: int,
        *,
        line_num: int,
        line_nums: List[int],
    ) -> Optional[int]:
        if not self.case_stack:
            self._emit_error('? CASE error')
            return None
        frame = self.case_stack[-1]
        if frame.branch_finished:
            return layout.exit_line
        if frame.branch_index is not None and branch_index != frame.branch_index:
            if branch_index > frame.branch_index:
                return layout.exit_line
            return self._next_case_branch_line(layout, branch_index)
        inline = layout.branch_inline[branch_index]
        if inline:
            frame.branch_finished = True
            result = self._execute_inline_statements(inline, line_num, line_nums)
            return layout.exit_line if result is None else result
        entry_line = self._case_branch_entry_line(layout, branch_index)
        if entry_line == line_num:
            entry_idx = self._line_index(entry_line, line_nums)
            if entry_idx + 1 < len(line_nums):
                return line_nums[entry_idx + 1]
            return layout.exit_line
        return entry_line

    def _decode_bbc_quoted_string(self, inner: str) -> str:
        out: List[str] = []
        index = 0
        while index < len(inner):
            ch = inner[index]
            if ch == '"':
                if index + 1 < len(inner) and inner[index + 1] == '"':
                    out.append('"')
                    index += 2
                    continue
                raise ValueError('expected string literal')
            out.append(ch)
            index += 1
        return ''.join(out)

    def _decode_string_literal(self, expr: str) -> str:
        expr = expr.strip()
        if len(expr) < 2 or expr[0] != '"' or expr[-1] != '"':
            raise ValueError('expected string literal')
        try:
            return json.loads(expr)
        except json.JSONDecodeError:
            return self._decode_bbc_quoted_string(expr[1:-1])

    def _decode_bbc_adjacent_string_literals(self, text: str) -> str:
        """Decode BBC chained literals: ``"one"'"two"`` → ``onetwo``."""
        text = text.strip()
        parts: List[str] = []
        index = 0
        while index < len(text):
            while index < len(text) and text[index].isspace():
                index += 1
            if index >= len(text):
                break
            if text[index] != '"':
                raise ValueError('expected string literal')
            end = index + 1
            while end < len(text) and text[end] != '"':
                end += 1
            if end >= len(text):
                raise ValueError('unterminated string literal')
            parts.append(self._decode_string_literal(text[index:end + 1]))
            index = end + 1
            while index < len(text) and text[index].isspace():
                index += 1
            if index < len(text) and text[index] == "'":
                peek = index + 1
                while peek < len(text) and text[peek].isspace():
                    peek += 1
                if peek < len(text) and text[peek] == '"':
                    index += 1
                    continue
            if index < len(text) and text[index] == '"':
                continue
            break
        if not parts:
            raise ValueError('expected string literal')
        return ''.join(parts)

    def _split_bbc_juxtaposed_string_parts(self, expr: str) -> List[str]:
        """Split BBC string juxtaposition: ``"Hi"STR$(n)`` or ``"a""b"``."""
        expr = expr.strip()
        parts: List[str] = []
        index = 0
        while index < len(expr):
            while index < len(expr) and expr[index].isspace():
                index += 1
            if index >= len(expr):
                break
            if expr[index] == '"':
                start = index
                while True:
                    if index >= len(expr) or expr[index] != '"':
                        break
                    end = index + 1
                    while end < len(expr) and expr[end] != '"':
                        end += 1
                    if end >= len(expr):
                        raise ValueError('unterminated string literal')
                    index = end + 1
                    while index < len(expr) and expr[index].isspace():
                        index += 1
                    if index < len(expr) and expr[index] == "'":
                        peek = index + 1
                        while peek < len(expr) and expr[peek].isspace():
                            peek += 1
                        if peek < len(expr) and expr[peek] == '"':
                            index += 1
                            continue
                    if index < len(expr) and expr[index] == '"':
                        continue
                    break
                parts.append(expr[start:index].strip())
                continue
            start = index
            depth = 0
            while index < len(expr):
                ch = expr[index]
                if ch == '"' and depth == 0:
                    break
                if ch == '(':
                    depth += 1
                elif ch == ')':
                    depth = max(0, depth - 1)
                elif ch == '+' and depth == 0:
                    break
                index += 1
            part = expr[start:index].strip()
            if part:
                parts.append(part)
        return parts or [expr]

    def _resolve_juxtaposed_string_part(self, part: str) -> str:
        part = part.strip()
        if part.startswith('"'):
            return self._decode_bbc_adjacent_string_literals(part)
        return self.eval_print_value(self._expand_dynamic_calls(part))

    def _split_string_concat(self, expr: str) -> List[str]:
        parts = self._split_at_depth(expr, '+', skip_empty=True)
        return parts or ['']

    def _resolve_string_atom(self, expr: str) -> str:
        expr = expr.strip()
        if expr.startswith('"'):
            return self._decode_bbc_adjacent_string_literals(expr)
        return self._resolve_string_value(expr)

    def _resolve_string_value(self, expr: str) -> str:
        expr = expr.strip()
        if self._looks_like_full_string_expr(expr):
            return self._eval_string_expr(expr)
        expr = self._expand_dynamic_calls(expr)
        upper = expr.upper()
        if upper == 'REPORT$':
            return self.error_message
        if upper == '@DIR$':
            return self._bbc_at_dir()
        if upper == '@LIB$':
            return self._bbc_at_lib()
        if upper == '@USR$':
            return self._bbc_at_usr()
        if upper == '@TMP$':
            return self._bbc_at_tmp()
        if upper == 'TIME$':
            return self._time_string()
        if self._expr_has_array_ref(expr):
            expr = self._substitute_array_references(expr)
            if expr.startswith('"'):
                return self._decode_bbc_adjacent_string_literals(expr)
        if expr.startswith('"'):
            return self._decode_bbc_adjacent_string_literals(expr)
        parsed = self._parse_array_lvalue(expr)
        if parsed is not None:
            base, kind, indices_expr = parsed
            if kind != 'str':
                raise ValueError('expected string value')
            return str(self._array_get(base, kind, self._eval_array_indices(indices_expr)))
        if re.fullmatch(r'INKEY\$', expr, re.IGNORECASE):
            return self._inkey_value()
        if re.fullmatch(r'GET\$', expr, re.IGNORECASE):
            code = self._read_get_char()
            return chr(code & 0xFF) if code else ''
        match = re.match(rf'^({self._VAR_BASE_PATTERN})\$$', expr)
        if match:
            return self.str_variables.get(
                self._normalize_identifier(match.group(1)),
                '',
            )
        # BBCSDL struct string member e.g. obj.name$   (full key 'obj.name$' in struct_members)
        dmatch = re.match(r'^(.+\..+)\$$', expr)
        if dmatch:
            key = dmatch.group(1) + '$'
            if key in self.struct_members:
                return str(self.struct_members[key])
            # also try without forcing if parse gave it
            if expr in self.struct_members:
                return str(self.struct_members[expr])
        raise ValueError(f"expected string value, got {expr}")

    def _ansi_sgr(self, *codes: int) -> str:
        return self._esc + '[' + ';'.join(str(int(c)) for c in codes) + 'm'

    def _looks_like_statement(self, text: str) -> bool:
        text = text.strip()
        if not text:
            return False
        cmd, _ = self._parse_command(text)
        if cmd:
            return True
        # Simple / compound assignment (same maximal-LHS rules as assign parse).
        # ``aand=0`` is a normal assignment, not ``a`` AND= 0.
        if '=' not in text:
            return False
        try:
            lhs, op, _rhs = self._parse_assignment_statement(text)
        except ValueError:
            return False
        if op != '=':
            self.dprint('[COMPOUND]', repr(text), repr(lhs), repr(op))
        if re.fullmatch(r'(OR|AND|EOR|XOR|DIV|MOD|NOT)', lhs, re.IGNORECASE):
            return False
        if self._parse_array_lvalue(lhs) is not None:
            return True
        if re.match(
            rf'^({self._VAR_BASE_PATTERN})([%$!#&]?)$',
            lhs,
            flags=self._identifier_re_flags(),
        ):
            return True
        return False

    def _classify_compact_if_branch(self, code: str, line_num: int) -> str:
        """Classify compact-IF branch code as statement, goto, or invalid."""
        del line_num  # goto validity depends on program/labels, not caller line
        code = code.strip()
        if not code:
            return 'empty'  # IF cond THEN  (no-op true branch)
        if self._in_fn_body and re.match(r'^=\s*.+', code):
            return 'statement'
        if self._looks_like_statement(code):
            return 'statement'
        if re.fullmatch(r'\d+', code):
            if not self._dialect_allows('if_then_line'):
                return 'invalid'
            return 'goto' if int(code) in self.program else 'invalid'
        if self._normalize_identifier(code) in self.labels:
            if not self._dialect_allows('if_then_line'):
                return 'invalid'
            return 'goto'
        return 'invalid'

    def _find_then_keyword(self, text: str) -> Optional[int]:
        """Index of THEN in compact IF rest (allows glued forms: ``P$THEN``, ``1THEN``).

        Classic MITS/BBC allow no space before THEN after digits/type suffixes.
        Do not match inside strings, or when THEN is part of an identifier (letter before).
        """
        in_string = False
        index = 0
        while index < len(text):
            ch = text[index]
            if ch == '"':
                in_string = not in_string
                index += 1
                continue
            if (
                not in_string
                and text[index:index + 4].upper() == 'THEN'
                and (index == 0 or not text[index - 1].isalpha())
                and (index + 4 >= len(text) or not text[index + 4].isalnum())
            ):
                return index
            index += 1
        return None

    def _split_bbc_compact_if_then(self, then_part: str) -> Tuple[str, str]:
        then_part = then_part.strip()
        then_at = self._find_then_keyword(then_part)
        if then_at is not None:
            condition = then_part[:then_at].strip()
            statement = then_part[then_at + 4:].strip()
            # Empty statement after THEN is a no-op (museum BETH: IF I$=P$THEN).
            if condition:
                return condition, statement
        # Spaced form still accepted via the same scan; fall back for BBC
        # "IF cond statement" without THEN (e.g. hanoi ``IF F>13 RUN``).
        # Prefer the *longest* condition (rightmost space split) whose tail
        # looks like a statement — do not require the condition to evaluate
        # successfully here (vars may not be ready; eval happens at execute).
        best: Optional[Tuple[str, str]] = None
        for match in re.finditer(r'\s+', then_part):
            condition = then_part[: match.start()].strip()
            statement = then_part[match.end() :].strip()
            if not condition or not statement:
                continue
            # MS/BBC: IF cond linenum  (no THEN) — e.g. IF Y$<>"N" 15
            # Do not let a trailing RHS number steal a real statement already
            # found: piechart ``IF Y% = Cy% + Depth Colour&() OR= 8``.
            if re.fullmatch(r'\d+', statement) and self._dialect_allows('if_then_line'):
                if best is None:
                    best = (condition, statement)
                continue
            if not self._looks_like_statement(statement):
                continue
            best = (condition, statement)
        if best is not None:
            return best
        # MS/BBC: IF Y$<>"N"15  (line number glued to the closing quote)
        glued = self._split_glued_string_linenum(then_part)
        if glued is not None:
            return glued
        # welcome: ``IF(I%AND1)=0:PLOT …`` — colon splits IF from body; condition
        # alone must still parse (body runs via trailing colon stmts).
        stripped = then_part.strip()
        if stripped and self._looks_like_if_condition_only(stripped):
            return stripped, ''
        raise ValueError('invalid IF syntax')

    def _split_glued_string_linenum(self, text: str) -> Optional[Tuple[str, str]]:
        """Split ``Y$<>\"N\"15`` into (``Y$<>\"N\"``, ``15``). Not ``IF A=15``."""
        if not self._dialect_allows('if_then_line'):
            return None
        in_string = False
        last_close = -1
        i = 0
        while i < len(text):
            if text[i] != '"':
                i += 1
                continue
            if in_string and i + 1 < len(text) and text[i + 1] == '"':
                i += 2
                continue
            in_string = not in_string
            if not in_string:
                last_close = i
            i += 1
        if in_string or last_close < 0:
            return None
        tail = text[last_close + 1 :].strip()
        if not re.fullmatch(r'\d+', tail):
            return None
        cond = text[: last_close + 1].strip()
        if not cond:
            return None
        return cond, tail

    def _looks_like_if_condition_only(self, text: str) -> bool:
        """True when text is a bare IF condition (no THEN, no trailing statement)."""
        text = text.strip()
        if not text or self._looks_like_statement(text):
            return False
        if self._find_then_keyword(text) is not None:
            return False
        # Not bare condition if a line number follows (IF cond 100 without THEN).
        if re.search(r'\s+\d+\s*$', text) and self._dialect_allows('if_then_line'):
            return False
        # Comparisons or parenthesized predicates, e.g. (I%AND1)=0
        if re.search(r'(<>|<=|>=|<|>|=)', text):
            return True
        return bool(re.search(r'\b(AND|OR|NOT|EOR|XOR)\b', text, re.IGNORECASE))

    def _if_error_detail(self, rest: str) -> str:
        """Extra hint for common compact-IF mistakes (esp. DEF FN returns)."""
        text = rest.strip()
        # IF cond =expr ELSE =expr  — missing THEN (DEF FN return style)
        if re.search(r'\bELSE\b', text, re.IGNORECASE) and not re.search(
            r'\bTHEN\b', text, re.IGNORECASE
        ):
            if re.search(r'=\s*\S', text):
                return (
                    'IF needs THEN before the branch '
                    '(DEF FN return: IF cond THEN =expr ELSE =expr)'
                )
            return 'IF needs THEN before the true-branch statement'
        # Only flag DEF-FN style when the first non-space after a comparison-like
        # ``=`` is itself ``=`` (``IF cond =expr``), not compact BBC
        # ``IF Y% = n Colour&() OR= 8`` (condition uses =, body is a statement).
        if not re.search(r'\bTHEN\b', text, re.IGNORECASE):
            m = re.match(r'^.+?\s+=\s*(=.*)$', text)
            if m:
                return (
                    'IF needs THEN before =return '
                    '(use: IF cond THEN =expr)'
                )
        return 'IF error'

    def _init_time_clock(self) -> None:
        """Start or restart the BBC-style centisecond clock at zero."""
        self.time_value = 0.0
        self.time_set_at = time.perf_counter()

    def _get_time(self) -> float:
        elapsed_cs = (time.perf_counter() - self.time_set_at) * 100.0
        return int(self.time_value + elapsed_cs)

    def _set_time(self, value: float) -> None:
        self.time_value = float(int(value))
        self.time_set_at = time.perf_counter()

    def _time_string(self) -> str:
        """BBC BASIC TIME$ — 24 characters: ``Day,dd Mon yyyy.hh:mm:ss``.

        jclock (and other demos) use ``VALMID$(Time$,17/20/23)`` for H/M/S.
        A short ``HH:MM:SS`` made those VAL 0 → all hands stacked at 12 o'clock.
        """
        import time
        # %a=Sun, %d=01..31, %b=Jan, %Y=2026, %H:%M:%S → 24 chars in C locale.
        return time.strftime('%a,%d %b %Y.%H:%M:%S')

    def _canonical_system_var_name(self, token: str) -> Optional[str]:
        """Map known mini_basic system vars (_case_sensitive, …).

        BBCSDL user identifiers may also start with ``_`` (e.g. flier ``_BOX``).
        Those are *not* system variables — return None so normal var/array
        paths handle them. Only names in ``_SYSTEM_VAR_SPEC`` are reserved.
        """
        token = token.strip()
        if not token.startswith('_'):
            return None
        if not re.fullmatch(r'_[A-Za-z][A-Za-z0-9_]*', token):
            return None
        key = token.lower()
        if key not in _SYSTEM_VAR_SPEC:
            return None
        return key

    def _get_system_var(self, name: str) -> float:
        key = self._canonical_system_var_name(name) or name
        # BBC ON ERROR: ERR / ERL must work in compiled IF conditions (piechart).
        upper = str(key).upper()
        if upper == 'ERR':
            return float(getattr(self, 'error_code_num', 0) or 0)
        if upper == 'ERL':
            return float(getattr(self, 'error_line_num', 0) or 0)
        if key == '_case_sensitive':
            override = self.config.identifiers_case_sensitive
            if override is None:
                return 2.0
            return 1.0 if override else 0.0
        spec = _SYSTEM_VAR_SPEC[key]
        target = self.config if spec['target'] == 'config' else self
        value = getattr(target, str(spec['attr']))
        if spec['kind'] == 'bool':
            return 1.0 if value else 0.0
        return float(value)

    def _set_system_var(self, name: str, value: float) -> None:
        key = self._canonical_system_var_name(name) or name
        spec = _SYSTEM_VAR_SPEC[key]
        if spec.get('readonly'):
            raise ValueError(f'read-only system variable: {name}')
        if spec['kind'] == 'bool':
            coerced = bool(int(value))
        else:
            coerced = int(value)
        coerced = max(int(spec['min']), min(int(spec['max']), coerced))
        if spec['kind'] == 'bool':
            coerced = bool(coerced)

        if key == '_case_sensitive':
            self.set_case_sensitivity(
                None if coerced == 2 else bool(coerced),
                announce=False,
            )
            return

        target = self.config if spec['target'] == 'config' else self
        setattr(target, str(spec['attr']), coerced)
        if key == '_optimization_level':
            self.config.__post_init__()
            self._compiled_expr_cache.clear()

    def _system_vars_in_expr(self, expr: str) -> Tuple[str, ...]:
        found: List[str] = []
        for name in _SYSTEM_VAR_SPEC:
            if re.search(rf'(?<![A-Za-z0-9_]){re.escape(name)}\b', expr):
                found.append(name)
        # BBC runtime error status (not underscore system vars; used in ON ERROR IF ERR=…)
        for name in ('ERR', 'ERL'):
            if re.search(rf'(?<![A-Za-z0-9_]){name}(?![A-Za-z0-9_$])', expr, re.IGNORECASE):
                # Keep source casing for eval namespace key (BBC uses ERR/ERL).
                m = re.search(
                    rf'(?<![A-Za-z0-9_])({name})(?![A-Za-z0-9_$])',
                    expr,
                    re.IGNORECASE,
                )
                if m and m.group(1) not in found:
                    found.append(m.group(1))
        return tuple(found)

    def _identifiers_case_sensitive(self) -> bool:
        """mini/bbc: case-sensitive by default; mits/com/tiny fold by default.

        When True (any dialect), statement keywords must also be the canonical
        uppercase form (``PRINT``, ``COLOUR``, ``FOR``) so mixed-case names are
        not stolen as commands. When False, keywords accept any case (``print``).
        Dialect still decides which keywords exist; only matching case changes.
        """
        override = self.config.identifiers_case_sensitive
        if override is not None:
            return override
        return self.config.dialect in ('mini', 'bbc')

    def _is_statement_keyword(self, token: str) -> bool:
        """True if token is a statement keyword under current case rules."""
        if not token:
            return False
        if self._identifiers_case_sensitive() and token != token.upper():
            return False
        return token.upper() in self._STMT_KEYWORDS

    def set_case_sensitivity(
        self,
        mode: Optional[bool],
        *,
        announce: bool = True,
    ) -> None:
        old_case = self._identifiers_case_sensitive()
        self.config.identifiers_case_sensitive = mode
        new_case = self._identifiers_case_sensitive()
        if old_case != new_case and self.program:
            self._clear_runtime_variables()
            if announce:
                print('Note: case mode changed — variable values cleared')
        self._definitions_dirty = True
        self._invalidate_program_caches()
        self._invalidate_run_prepare_caches()
        if announce:
            if mode is None:
                print('Case: auto (follows dialect)')
            else:
                print(f'Case: {"on" if mode else "off"}')

    def _var_significant_length(self) -> int:
        """Return how many characters of a variable name are significant.
        0 or large = full name (BBC, mini, modern).
        2 = classic Microsoft BASICs (Commodore, MS, AppleSoft etc.) where only
        first two letters + type suffix matter. This can cause collisions like
        PISTEET and PISTOLA both being "PI".
        """
        if self._identifiers_case_sensitive():
            return 0  # full significance
        dialect = self.config.dialect
        if dialect in ('bbc', 'mini'):
            return 0
        # commodore, mits, tiny etc. classic 2-letter significance
        return 2

    def _loop_var_matches(self, left: str, right: str) -> bool:
        """True when two FOR/NEXT variable names refer to the same loop counter."""
