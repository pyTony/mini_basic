    def _split_colon_statements(self, line: str) -> List[str]:
        stripped = line.strip()
        if stripped.startswith("'") or stripped.upper().startswith("REM"):
            return [stripped]
        # BBC event handlers keep their full colon tail:
        #   ON CLOSE PROC cleanup : QUIT
        #   ON ERROR PROC cleanup : IF ERR=17 … ELSE …
        # (keywords.txt: ON CLOSE [LOCAL] <stmt>{:<stmt>}[:RETURN])
        if re.match(
            r'^ON\s+(CLOSE|ERROR|MOUSE|MOVE|SYS|TIME)\b',
            stripped,
            re.IGNORECASE,
        ):
            return [stripped]
        parts: List[str] = []
        current: List[str] = []
        in_string = False
        after_then = False
        index = 0
        while index < len(line):
            ch = line[index]
            if ch == '"':
                in_string = not in_string
                current.append(ch)
                index += 1
                continue
            if (
                not in_string
                and not after_then
                and line[index:index + 4].upper() == 'THEN'
                and (index == 0 or not line[index - 1].isalnum())
                and (index + 4 >= len(line) or not line[index + 4].isalnum())
            ):
                after_then = True
                current.append(line[index:index + 4])
                index += 4
                continue
            if ch == ':' and not in_string:
                part = ''.join(current).strip()
                if part.upper().startswith('REM') or part.lstrip().startswith("'"):
                    current.append(ch)
                    index += 1
                    continue
                if after_then:
                    current.append(ch)
                    index += 1
                    continue
                if part:
                    head_cmd, _ = self._parse_command(part)
                    if head_cmd in ('WHEN', 'OTHERWISE'):
                        current.append(ch)
                        index += 1
                        continue
                head_cmd, _ = self._parse_command(part)
                if (
                    part
                    and not head_cmd  # if it parses as a command (even glued like printj), : is separator not label
                    and self._RE_VAR_BASE_FULL.fullmatch(part)
                    and not self._is_statement_keyword(part)
                ):
                    current.append(ch)
                    index += 1
                    continue
                if part:
                    parts.append(part)
                current = []
                after_then = False
                index += 1
                continue
            current.append(ch)
            index += 1
        part = ''.join(current).strip()
        if part:
            parts.append(part)
        return parts

