    def _bbcsdl_vdu_word(self, offset: int) -> int:
        """BBCSDL ``@vdu%!offset`` system structure (common piechart/aspect fields).

        208 / 212 = graphics width / height in *pixels* (wiki). With OS scale 2
        those values sit at the screen centre in OS coordinates — piechart uses
        them as Cx%/Cy%. 220 ≈ character height in OS units.
        """
        width = int(self.config.graphics_width or 640)
        height = int(self.config.graphics_height or 512)
        y_scale = 2
        try:
            from ..bbc_modes import bbc_os_scales

            _xs, y_scale = bbc_os_scales(width, height)
        except Exception:
            pass
        cell_h = 8
        if self._display_enabled() and hasattr(self._display, 'cell_height'):
            cell_h = int(getattr(self._display, 'cell_height', 8) or 8)
        table = {
            208: width,
            212: height,
            220: cell_h * max(1, y_scale),
        }
        return int(table.get(int(offset), 0))

    def _substitute_bbcsdl_special_vars(self, expr: str) -> str:
        width = self.config.graphics_width or 1280
        height = self.config.graphics_height or 1024
        # @vdu%!n indirection before bare @vdu%
        def _vdu_ind(match: re.Match) -> str:
            return str(self._bbcsdl_vdu_word(int(match.group(1))))

        # Allow spaces around % / ! so broken unglue forms like ``@VDU %!220``
        # still resolve (piechart label MOVE).
        expr = re.sub(
            r'(?<![A-Za-z0-9_])@vdu\s*%\s*!\s*(\d+)',
            _vdu_ind,
            expr,
            flags=re.IGNORECASE,
        )
        replacements = {
            '@platform%': '64' if sys.maxsize > 2 ** 32 else '0',
            '@hwnd%': '1',
            '@memhdc%': '1',
            '@ispal%': '0',
            '@vdu%': '0',
            '@vdu.tr%': str(width),
            '@vdu.tb%': str(height),
            '@size.x%': str(width),
            '@size.y%': str(height),
        }
        for token, value in replacements.items():
            expr = re.sub(
                rf'(?<![A-Za-z0-9_]){re.escape(token)}',
                value,
                expr,
                flags=re.IGNORECASE,
            )
        return expr

    def _split_at_depth(
        self,
        text: str,
        delim: str,
        *,
        skip_empty: bool = False,
        preserve_trailing: bool = False,
    ) -> List[str]:
        """Split text by delimiter at depth 0, respecting strings and parentheses."""

        def _normalize_part(raw: str) -> str:
            return raw.lstrip() if preserve_trailing else raw.strip()
        parts: List[str] = []
        current: List[str] = []
        depth = 0
        in_string = False
        i = 0
        n = len(text)

        while i < n:
            ch = text[i]
            if ch == '"':
                current.append(ch)
                if i + 1 < n and text[i + 1] == '"':
                    # escaped "" (either inside open string or empty literal handling)
                    i += 1
                    current.append(text[i])
                    # do not flip in_string for escaped pair; it stays as-is or will be handled by next "
                else:
                    in_string = not in_string
            elif not in_string:
                if ch == '(':
                    depth += 1
                    current.append(ch)
                elif ch == ')':
                    depth = max(0, depth - 1)
                    current.append(ch)
                elif ch == '{':
                    depth += 1
                    current.append(ch)
                elif ch == '}':
                    depth = max(0, depth - 1)
                    current.append(ch)
                elif ch == delim and depth == 0:
                    part = _normalize_part(''.join(current))
                    if not skip_empty or part:
                        parts.append(part)
                    current = []
                else:
                    current.append(ch)
            else:
                current.append(ch)
            i += 1

        part = _normalize_part(''.join(current))
        if not skip_empty or part:
            parts.append(part)
        return parts

    def _split_first_at_depth(self, text: str, delim: str) -> Tuple[str, str]:
        """Split at the first delimiter at depth 0. Returns (before, after)."""
        if not text:
            return '', ''

        depth = 0
        in_string = False
        i = 0
        n = len(text)

        while i < n:
            ch = text[i]
            if ch == '"':
                in_string = not in_string
                if in_string and i + 1 < n and text[i + 1] == '"':
                    i += 1
            elif not in_string:
                if ch == '(':
                    depth += 1
                elif ch == ')':
                    depth = max(0, depth - 1)
                elif ch == delim and depth == 0:
                    return text[:i].strip(), text[i + 1:].strip()
            i += 1

        return text.strip(), ''

