    def _append_indented_continuation(
        self,
        numbered: List[Tuple[int, str, int]],
        statement: str,
        indent: int,
    ) -> None:
        if not numbered:
            raise ValueError('indented continuation without a numbered line')
        line_num, prev_stmt, prev_indent = numbered[-1]
