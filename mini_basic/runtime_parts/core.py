    def _tee_apply_terminal_char(
        self,
        buffer: List[str],
        code: str,
        limit: int,
    ) -> bool:
        if code in ('\r', '\n'):
            self._tee_finish_input_line()
            return True
        if code == '\x03':
            raise KeyboardInterrupt
        if code in ('\x08', '\x7f'):
            if buffer:
                buffer.pop()
                self._tee_emit_input_backspace()
            return False
        if code in ('\x00', '\xe0'):
            if sys.platform == 'win32':
                import msvcrt
                msvcrt.getwch()
            return False
        if code.isprintable() and len(buffer) < limit:
            buffer.append(code)
            self._tee_emit_input_char(code)
        return False

    def _ensure_ansi_console(self) -> None:
        if self._ansi_console_tried:
            return
        self._ansi_console_tried = True
        if self._program_stdout is not None:
            self._ansi_console_enabled = False
            return
        for stream in (sys.stdout, sys.stderr):
            reconfigure = getattr(stream, 'reconfigure', None)
            if callable(reconfigure):
                try:
                    reconfigure(write_through=True)
                except Exception:
                    pass
        if sys.platform != 'win32':
            self._ansi_console_enabled = True
        else:
            try:
                import ctypes
                kernel32 = ctypes.windll.kernel32
                # stdout: enable VT processing so FG$/ANSI colours work
                handle_out = kernel32.GetStdHandle(-11)  # STD_OUTPUT_HANDLE
                mode_out = ctypes.c_ulong()
                enable_vt = 0x0004  # ENABLE_VIRTUAL_TERMINAL_PROCESSING
                if kernel32.GetConsoleMode(handle_out, ctypes.byref(mode_out)):
                    self._saved_console_mode = mode_out.value
                    if kernel32.SetConsoleMode(handle_out, mode_out.value | enable_vt):
                        self._ansi_console_enabled = True
                # stdin: save so we can restore line/echo/mouse flags after RUN
                handle_in = kernel32.GetStdHandle(-10)  # STD_INPUT_HANDLE
                mode_in = ctypes.c_ulong()
                if kernel32.GetConsoleMode(handle_in, ctypes.byref(mode_in)):
                    self._saved_console_mode_in = mode_in.value
            except Exception:
                self._ansi_console_enabled = False

        # Never enter the alternate screen here. Streaming PRINT uses the
        # normal scrollback. Grid mode (goto) may enter alt-screen later;
        # _restore_console always leaves it and resets terminal modes so
        # PowerShell scrollback / PSReadLine keep working after exit.

