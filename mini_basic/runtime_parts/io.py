    def _print_program_text(self, text: str, newline: bool) -> None:
        # Immediate mode (REPL ``PRINT`` after RUN): stay on the terminal.
        # Re-opening pygame here hid the numbers on the graphics window, and
        # poll() treating Esc as QUIT then raised ProgramExit → Goodbye!
        immediate = getattr(self, '_active_line_num', -1) == 0
        if not (immediate and not self._display_live):
            self._ensure_display()
        if newline and text and text[-1] == '\n':
            newline = False
        if self._display_enabled():
            if self._terminal_tee_enabled() or immediate:
                if text:
                    self._tee_terminal_write(text)
                if newline:
                    self._tee_terminal_write('\n')
            if text:
                self._display_write_vdu_string(text)
            if newline:
                self._display.newline()
                self._print_finish_line()
            if self._refresh_enabled and hasattr(self._display, 'mark_dirty'):
                self._display.mark_dirty()
            if not self._display.poll():
                if immediate:
                    self._mark_display_closed()
                else:
                    self._invoke_on_close_and_exit()
            return
        if text:
            prefix = self._colour_prefix_for_output()
            if prefix:
                text = prefix + text
        if self.config.print_line_buffering:
            self._print_line_parts.append(text)
            if newline:
                self._print_line_parts.append('\n')
                self._print_flush_buffer()
                self._print_finish_line()
            return
        if text:
            self._console_write_buffer.append(text)
        if newline:
            self._console_write_buffer.append('\n')
            self._print_finish_line()
            # Be lazy with flushes for terminal mode: high volume of PRINT TAB / positioned
            # output (as in RACE.BBC etc) would otherwise cause many small writes + flushes,
            # which is very slow on Windows console. Flush on volume or at sync points
            # (CLS, before input, shutdown, etc).
            if len(self._console_write_buffer) > 2048:
                self._flush_program_output()

