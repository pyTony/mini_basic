    def _execute_on_goto_gosub(
        self,
        expr: str,
        kind: str,
        targets_rest: str,
        line_num: int,
        line_nums: List[int],
        stmt_index: int,
        stmt_count: int,
    ) -> Optional[int]:
        if not self._dialect_allows('on_goto_gosub'):
            self._emit_error('? ON GOTO/GOSUB error: not allowed in this dialect')
            return None
        try:
            index = int(self._eval_numeric(expr.strip()))
            targets = [
                token.strip()
                for token in self._split_args(targets_rest)
                if token.strip()
            ]
            if index < 1 or index > len(targets):
                # Classic BASIC: out-of-range ON is a no-op (no branch).
                return None
            target_token = targets[index - 1]
            if kind.upper() == 'GOSUB':
                if stmt_index + 1 < stmt_count:
                    self.gosub_stack.append((line_num, stmt_index + 1))
                else:
                    self.gosub_stack.append((self._next_line_num(line_num, line_nums), 0))
            return self.resolve_jump_target(target_token)
        except Exception as exc:
            self._emit_error(self._error_message('? ON GOTO/GOSUB error', exc))
            return None

