    def _prepare_run(self) -> None:
        self._run_line_nums = sorted(self.program.keys())
        self._run_line_index = {num: idx for idx, num in enumerate(self._run_line_nums)}
        self._run_stmts = {}
        self._run_for_next = {}
        self._run_while_wend = {}
        self._run_repeat_until = {}
        if self.config.use_run_caches:
            self._run_stmts = {
                line_num: self._parse_line_statements(text)
                for line_num, text in self.program.items()
            }
            for line_num in self._run_line_nums:
                for stmt_idx, (_, text) in enumerate(self._run_stmts[line_num]):
                    cmd, rest = self._parse_command(text)
                    if cmd == 'FOR':
                        match = self._match_for_clause(rest)
                        if match:
                            loop_var, _ = self._parse_var_token(match.group(1) + match.group(2))
                            next_stmt = self._find_matching_next_stmt_index(
                                loop_var,
                                self._run_stmts[line_num],
                                stmt_idx + 1,
                            )
                            if next_stmt >= 0:
                                self._run_for_next[(line_num, loop_var)] = line_num
                            else:
                                self._run_for_next[(line_num, loop_var)] = self._find_matching_next(
                                    loop_var, line_num, self._run_line_nums
                                )
                    elif cmd == 'WHILE':
                        self._run_while_wend[line_num] = self._find_matching_wend(
                            line_num, self._run_line_nums
                        )
                    elif cmd == 'REPEAT':
                        until_line, until_cond = self._find_matching_until(
                            line_num, self._run_line_nums
                        )
                        if until_line != -1:
                            self._run_repeat_until[line_num] = (until_line, until_cond)
        self._var_subst_int_entries = []
        self._var_subst_float_entries = []
        self._compiled_expr_cache = {}
        self._parse_command_cache = {}
        self._assign_parse_cache = {}
        if self.config.use_compiled_exprs:
            self._warm_compiled_exprs()
        self._build_data_table()
        self._build_user_functions()
        self._build_user_procedures()
        self._definitions_dirty = False

    def _prepare_expr_for_compile(
        self,
        expr: str,
        is_condition: bool,
        *,
        allow_bitwise: bool = False,
    ) -> Tuple[str, bool, Tuple[str, ...], Tuple[str, ...], Tuple[str, ...]]:
        if self._RE_FN_CALL.search(expr):
            raise ValueError('dynamic call in expression')
        if self._RE_FUNC_CALL.search(expr):
            raise ValueError('dynamic builtin in expression')
        if self._RE_NUMERIC_FUNC_CALL.search(expr):
            raise ValueError('dynamic numeric builtin in expression')
        if self._RE_FILE_FUNC.search(expr) or self._RE_FILE_FUNC_BBC.search(expr):
            raise ValueError('dynamic file function in expression')
        if self._expr_has_boolean_syntax(expr):
            if not (allow_bitwise and self._expr_is_pure_bitwise(expr)):
                raise ValueError('boolean expression')
        if is_condition:
            # strip: \bnot\b → ' NOT ' can leave a leading space → IndentationError
            expr = self._normalize_condition(expr).strip()
        # TRUE/FALSE must become -1/0 before compile(); else Python NameError.
        expr = self._substitute_boolean_literals(expr)
        expr = self._substitute_bbc_hex_literals(expr)
        expr = self._substitute_bbc_numeric_constants(expr)
        expr = self._substitute_bbc_memory_vars(expr)
        if re.search(r'(?<![A-Za-z0-9_])@%\b', expr):
            expr = re.sub(
                r'(?<![A-Za-z0-9_])@%\b',
                str(self.bbc_at_percent),
                expr,
            )
        # Bitwise words → Python operators before int-slot rewrite.
        expr = self._normalize_operators(expr)
        needs_time = bool(self._RE_TIME.search(expr))
        if needs_time:
            expr = self._RE_TIME.sub('__basic_time__', expr)
        expr, int_vars = self._replace_int_vars_for_compile(expr)
        expr = self._canonicalize_expr_identifiers(expr)
        system_vars = self._system_vars_in_expr(expr)
        float_vars = self._extract_float_vars_for_compile(expr)
        return expr, needs_time, float_vars, int_vars, system_vars

    def _prepare_simple_comparison_for_compile(
        self, expr: str,
    ) -> Tuple[str, bool, Tuple[str, ...], Tuple[str, ...], Tuple[str, ...]]:
        expr = expr.strip()
        index = self._boolean_skip_ws(expr, 0)
        left_end = self._boolean_find_arith_end(expr, index)
        left_fragment = expr[index:left_end].strip()
        if not left_fragment:
            raise ValueError('expected expression')
        index = left_end
        index = self._boolean_skip_ws(expr, index)
        op = self._boolean_relop_at(expr, index)
        if op is None:
            raise ValueError('expected comparison operator')
        py_op = {'=': '==', '==': '==', '<>': '!=', '!=': '!='}.get(op, op)
        index += len(op)
        right_end = self._boolean_find_arith_end(expr, index)
        right_fragment = expr[index:right_end].strip()
        if not right_fragment:
            raise ValueError('expected expression')
        if self._boolean_skip_ws(expr, right_end) < len(expr):
            raise ValueError('trailing syntax')
        if (
            self._fragment_is_string_expr(left_fragment)
            or self._fragment_is_string_expr(right_fragment)
        ):
            raise ValueError('string comparison')
        left_py, needs_time_l, float_l, int_l, sys_l = self._prepare_expr_for_compile(
            left_fragment,
            False,
        )
        right_py, needs_time_r, float_r, int_r, sys_r = self._prepare_expr_for_compile(
            right_fragment,
            False,
        )
        return (
            f'(-1 if ({left_py}) {py_op} ({right_py}) else 0)',
            needs_time_l or needs_time_r,
            tuple(dict.fromkeys(float_l + float_r)),
            tuple(dict.fromkeys(int_l + int_r)),
            tuple(dict.fromkeys(sys_l + sys_r)),
        )

    def _prepare_mixed_boolean_for_compile(
        self, expr: str,
    ) -> Tuple[str, bool, Tuple[str, ...], Tuple[str, ...], Tuple[str, ...]]:
        """Compile AND/OR/NOT/XOR chains that mix comparisons and values.

        Shapes like ``CONT AND (I% < MAXITER%)`` and ``A < B AND B < C`` lower
        comparisons to BBC -1/0 then combine with Python ``&``/``|``/``^``/``~``.
        EQV/IMP and string comparisons stay on the slow path.
        """
        expr = expr.strip()
        if not expr:
            raise ValueError('empty boolean')
        if re.search(r'\b(EQV|IMP)\b', expr, re.IGNORECASE):
            raise ValueError('boolean expression')
        if self._expr_has_xor_eqv_imp_eor(expr):
            py, end, needs_time, float_vars, int_vars, system_vars = (
                self._compile_boolean_or_with_xor(expr, 0)
            )
        else:
            py, end, needs_time, float_vars, int_vars, system_vars = (
                self._compile_boolean_or_simple(expr, 0)
            )
        if self._boolean_skip_ws(expr, end) < len(expr):
            raise ValueError('trailing syntax')
        return py, needs_time, float_vars, int_vars, system_vars

    def _compile_bool_merge(
        self,
        *parts: Tuple[bool, Tuple[str, ...], Tuple[str, ...], Tuple[str, ...]],
    ) -> Tuple[bool, Tuple[str, ...], Tuple[str, ...], Tuple[str, ...]]:
        needs_time = any(p[0] for p in parts)
        float_vars: Tuple[str, ...] = ()
        int_vars: Tuple[str, ...] = ()
        system_vars: Tuple[str, ...] = ()
        for _, f, i, s in parts:
            float_vars = tuple(dict.fromkeys(float_vars + f))
            int_vars = tuple(dict.fromkeys(int_vars + i))
            system_vars = tuple(dict.fromkeys(system_vars + s))
        return needs_time, float_vars, int_vars, system_vars

    def _compile_boolean_or_simple(
        self, expr: str, index: int,
    ) -> Tuple[str, int, bool, Tuple[str, ...], Tuple[str, ...], Tuple[str, ...]]:
        left, index, nt, fv, iv, sv = self._compile_boolean_and(expr, index)
        while True:
            index = self._boolean_skip_ws(expr, index)
            if not self._boolean_keyword_at(expr, index, 'OR'):
                break
            index += 3
            right, index, nt_r, fv_r, iv_r, sv_r = self._compile_boolean_and(expr, index)
            left = f'({left} | {right})'
            nt, fv, iv, sv = self._compile_bool_merge(
                (nt, fv, iv, sv), (nt_r, fv_r, iv_r, sv_r),
            )
        return left, index, nt, fv, iv, sv

    def _compile_boolean_or_with_xor(
        self, expr: str, index: int,
    ) -> Tuple[str, int, bool, Tuple[str, ...], Tuple[str, ...], Tuple[str, ...]]:
        """OR chain over XOR/EOR (no EQV/IMP — those raise earlier)."""
        left, index, nt, fv, iv, sv = self._compile_boolean_xor(expr, index)
        while True:
            index = self._boolean_skip_ws(expr, index)
            if not self._boolean_keyword_at(expr, index, 'OR'):
                break
            index += 3
            right, index, nt_r, fv_r, iv_r, sv_r = self._compile_boolean_xor(expr, index)
            left = f'({left} | {right})'
            nt, fv, iv, sv = self._compile_bool_merge(
                (nt, fv, iv, sv), (nt_r, fv_r, iv_r, sv_r),
            )
        return left, index, nt, fv, iv, sv

    def _compile_boolean_xor(
        self, expr: str, index: int,
    ) -> Tuple[str, int, bool, Tuple[str, ...], Tuple[str, ...], Tuple[str, ...]]:
        left, index, nt, fv, iv, sv = self._compile_boolean_and(expr, index)
        while True:
            index = self._boolean_skip_ws(expr, index)
            xor_len = None
            for word in ('XOR', 'EOR'):
                if self._boolean_keyword_at(expr, index, word):
                    xor_len = len(word)
                    break
            if xor_len is None:
                break
            index += xor_len
            right, index, nt_r, fv_r, iv_r, sv_r = self._compile_boolean_and(expr, index)
            left = f'({left} ^ {right})'
            nt, fv, iv, sv = self._compile_bool_merge(
                (nt, fv, iv, sv), (nt_r, fv_r, iv_r, sv_r),
            )
        return left, index, nt, fv, iv, sv

    def _compile_boolean_and(
        self, expr: str, index: int,
    ) -> Tuple[str, int, bool, Tuple[str, ...], Tuple[str, ...], Tuple[str, ...]]:
        left, index, nt, fv, iv, sv = self._compile_boolean_not(expr, index)
        while True:
            index = self._boolean_skip_ws(expr, index)
            if not self._boolean_keyword_at(expr, index, 'AND'):
                break
            index += 3
            right, index, nt_r, fv_r, iv_r, sv_r = self._compile_boolean_not(expr, index)
            left = f'({left} & {right})'
            nt, fv, iv, sv = self._compile_bool_merge(
                (nt, fv, iv, sv), (nt_r, fv_r, iv_r, sv_r),
            )
        return left, index, nt, fv, iv, sv

    def _compile_boolean_not(
        self, expr: str, index: int,
    ) -> Tuple[str, int, bool, Tuple[str, ...], Tuple[str, ...], Tuple[str, ...]]:
        index = self._boolean_skip_ws(expr, index)
        if self._boolean_keyword_at(expr, index, 'NOT'):
            index += 3
            inner, index, nt, fv, iv, sv = self._compile_boolean_not(expr, index)
            return f'(~{inner})', index, nt, fv, iv, sv
        return self._compile_boolean_comparison(expr, index)

    def _compile_boolean_comparison(
        self, expr: str, index: int,
    ) -> Tuple[str, int, bool, Tuple[str, ...], Tuple[str, ...], Tuple[str, ...]]:
        index = self._boolean_skip_ws(expr, index)
        if index < len(expr) and expr[index] == '(':
            end = self._match_paren(expr, index)
            if end >= 0:
                inner = expr[index + 1:end]
                # Parenthesized comparison or boolean: (I% < N), (A AND B)
                if (
                    self._boolean_relop_at(
                        inner, self._boolean_find_arith_end(inner, 0),
                    )
                    is not None
                    or self._expr_has_boolean_syntax(inner)
                ):
                    if self._expr_has_xor_eqv_imp_eor(inner):
                        py, i2, nt, fv, iv, sv = self._compile_boolean_or_with_xor(
                            inner, 0,
                        )
                    else:
                        py, i2, nt, fv, iv, sv = self._compile_boolean_or_simple(
                            inner, 0,
                        )
                    if self._boolean_skip_ws(inner, i2) < len(inner.strip()):
                        raise ValueError('trailing syntax')
                    return f'({py})', end + 1, nt, fv, iv, sv

        left_end = self._boolean_find_arith_end(expr, index)
        left_fragment = expr[index:left_end].strip()
        if not left_fragment:
            raise ValueError('expected expression')
        index = self._boolean_skip_ws(expr, left_end)
        op = self._boolean_relop_at(expr, index)
        if op is None:
            left_py, nt, fv, iv, sv = self._prepare_expr_for_compile(
                left_fragment, False, allow_bitwise=self._expr_is_pure_bitwise(left_fragment),
            )
            # Bitwise AND/OR with floats (TRUE=-1.0) needs int operands.
            return f'int({left_py})', left_end, nt, fv, iv, sv
        py_op = {'=': '==', '==': '==', '<>': '!=', '!=': '!='}.get(op, op)
        index += len(op)
        right_end = self._boolean_find_arith_end(expr, index)
        right_fragment = expr[index:right_end].strip()
        if not right_fragment:
            raise ValueError('expected expression')
        if (
            self._fragment_is_string_expr(left_fragment)
            or self._fragment_is_string_expr(right_fragment)
        ):
            raise ValueError('string comparison')
        left_py, nt_l, fv_l, iv_l, sv_l = self._prepare_expr_for_compile(
            left_fragment, False,
        )
        right_py, nt_r, fv_r, iv_r, sv_r = self._prepare_expr_for_compile(
            right_fragment, False,
        )
        nt, fv, iv, sv = self._compile_bool_merge(
            (nt_l, fv_l, iv_l, sv_l), (nt_r, fv_r, iv_r, sv_r),
        )
        py = f'(-1 if ({left_py}) {py_op} ({right_py}) else 0)'
        return py, right_end, nt, fv, iv, sv

    def _extract_label_prefix(self, part: str) -> Tuple[Optional[str], str]:
        match = re.match(rf'^({self._VAR_BASE_PATTERN}):\s*(.*)$', part.strip())
        if match and not self._is_statement_keyword(match.group(1)):
            return self._normalize_identifier(match.group(1)), match.group(2).strip()
        return None, part.strip()

    def _rebuild_labels(self):
        self.labels.clear()
        for line_num in sorted(self.program):
            parts = self._split_colon_statements(self.program[line_num])
            if not parts:
                continue
            label, _ = self._extract_label_prefix(parts[0])
            if label:
                self.labels[label] = line_num

    def _program_statements_use_graphics(
        self,
        parsed_lines: List[Tuple[int, str, int]],
    ) -> bool:
        for _, statement, _ in parsed_lines:
            for part in self._split_colon_statements(statement):
                _, text = self._extract_label_prefix(part)
                if not text:
                    continue
                cmd, _ = self._parse_command(text)
                if cmd in self._GRAPHICS_CMDS:
                    return True
                # For bbc dialect, CLS / MODE / VDU / CLG / COLOUR etc. auto-enable pygame
                # (to support BBC screen programs). Pure PRINT-only text programs stay terminal.
                if self.config.dialect == 'bbc' and cmd in self._BBC_DISPLAY_CMDS:
                    return True
        return False

    def _maybe_auto_enable_pygame_from_program(self, *, announce: bool = True) -> None:
        """RUN: enable pygame when the loaded/typed program needs a display."""
        if not self.program:
            return
        parsed_lines = [
            (line_num, statement, self.line_indent.get(line_num, 0))
            for line_num, statement in sorted(self.program.items())
        ]
        self._maybe_auto_enable_pygame_display(parsed_lines, announce=announce)

    def _current_program_parsed_lines(self) -> List[Tuple[int, str, int]]:
        return [
            (line_num, statement, self.line_indent.get(line_num, 0))
            for line_num, statement in sorted(self.program.items())
        ]

    def _program_uses_refresh_off(self) -> bool:
        """True if the program turns automatic refresh off (draw then *REFRESH)."""
        for _, statement, _ in self._current_program_parsed_lines():
            for part in self._split_colon_statements(statement):
                raw = part.strip().lstrip('*').strip().upper()
                if raw.startswith('REFRESH') and raw[7:].strip().startswith('OFF'):
                    return True
        return False

    def _apply_program_refresh_off_at_start(self) -> None:
        """Don't flash MODE/COLOUR before the first *REFRESH (REPL second RUN)."""
        if not self._program_uses_refresh_off():
            return
        self._refresh_enabled = False
        if self._display is not None:
            setattr(self._display, '_refresh_enabled', False)

    def _announce_program_graphics(self) -> None:
        if not self.program:
            return
        if not self._program_statements_use_graphics(self._current_program_parsed_lines()):
            return
        backend = self._display_backend_name()
        # Tests / --display none: MODE/VDU must not leak a banner into stdout.
        if backend in ('none', 'null'):
            return
        name = os.path.basename(self.loaded_filename or '') or 'program'
        print(f'Graphics: {name} ({backend})', file=self._get_error_stream())

    def _scan_statement_dialect_violations(self, statement: str) -> List[str]:
        violations: List[str] = []
        for part in self._split_colon_statements(statement):
            _, text = self._extract_label_prefix(part)
            if not text:
                continue
            stripped = text.strip()
            if self._is_comment_statement(stripped):
                continue
            if re.match(r'^ON\s+CLOSE\b', stripped, re.IGNORECASE):
                if not self._dialect_allows('on_close'):
                    violations.append('on_close')
                continue
            if self._RE_ON_ERROR.match(stripped):
                if not self._dialect_allows('on_error_goto'):
                    violations.append('on_error_goto')
                continue
            on_match = self._RE_ON_GOTO_GOSUB.match(stripped)
            if on_match:
                if not self._dialect_allows('on_goto_gosub'):
                    violations.append('on_goto_gosub')
                continue
            cmd, rest = self._parse_command(text)
            if cmd in self._MITS_FORBIDDEN_CMDS and not self._dialect_allows(cmd):
                violations.append(cmd)
            elif cmd in self._MINI_ONLY_CMDS and not self._dialect_allows(cmd):
                violations.append(cmd)
            if cmd == 'DEF' and not re.search(r'\)\s*=', rest):
                if not self._dialect_allows('multiline_def'):
                    violations.append('multiline_def')
            if cmd == 'IF':
                if self._match_if_goto(rest) and not self._dialect_allows('if_goto'):
                    violations.append('if_goto')
                elif self._if_rest_uses_then_line_jump(rest):
                    violations.append('if_then_line')
            upper = text.upper()
            if re.search(r'\bINSTR\b', upper) and not self._dialect_allows('INSTR'):
                violations.append('INSTR')
            for func in self._MINI_ONLY_FUNCS:
                if re.search(rf'\b{re.escape(func)}\b', upper):
                    if not self._dialect_allows(func):
                        violations.append(func)
        return violations

    @classmethod
    def _normalize_hash_file_commands(cls, line: str) -> str:
        """BBC file I/O: PRINT #ch  INPUT #ch  CLOSE #ch  ->  PRINT#ch etc."""
        return cls._RE_HASH_FILE_CMD.sub(r'\1#', line.strip())

    @staticmethod
    def _space_glued_to_step(text: str, *, ignore_case: bool = True) -> str:
        """Space TO/STEP after a numeric literal or %) — not mid-identifier.

        ``1TO10``, ``10TO20``, ``I%TO``, ``)TO`` unglue. ``a0to+1`` and
        ``i00to+1`` stay one name (the digits belong to the identifier).
        """
        flags = re.IGNORECASE if ignore_case else 0
        # Separate TO then STEP so ``1TO10STEP2`` spaces both in one pass
        # (a single (TO|STEP) match would consume ``1TO`` and leave ``10STEP2``).
        # Also ``1TO M8`` (detokenize: digit + TO keyword + space + name).
        glued = r'[0-9A-Za-z_(+-]|\s|$'
        text = re.sub(
            rf'(?<![A-Za-z0-9_])([0-9]+)TO(?={glued})',
            r'\1 TO ',
            text,
            flags=flags,
        )
        text = re.sub(
            rf'(?<![A-Za-z0-9_])([0-9]+)STEP(?={glued})',
            r'\1 STEP ',
            text,
            flags=flags,
        )
        text = re.sub(
            rf'(?<=[%!)])(TO|STEP)(?={glued})',
            r' \1 ',
            text,
            flags=flags,
        )
        return text

