    def _parse_assignment_statement(self, line: str) -> Tuple[str, str, str]:
        """Return (lvalue, operator, rhs) for = / += / -= / *= / /= / OR= / AND= / …

        Arithmetic compounds: ``+=`` ``-=`` ``*=`` ``/=``.
        Bitwise compounds (BBC array ops, piechart): ``OR=`` ``AND=`` ``EOR=`` ``XOR=``
        only after a complete LHS (so ``aand=0`` stays assignment to ``aand``).

        Array LHS uses balanced parentheses so
        ``Value() *= 2 * PI / SUM(Value())`` and
        ``Colour&() OR= 8`` parse correctly.
        """
        cache = getattr(self, '_assign_parse_cache', None)
        if cache is not None:
            hit = cache.get(line)
            if hit is not None:
                return hit

        self.dprint('[ASSIGN]', repr(line))

        def _remember(triple: Tuple[str, str, str]) -> Tuple[str, str, str]:
            if cache is not None:
                cache[line] = triple
            return triple

        text = line.strip()
        if text.upper().startswith("LET"):
            text = text[3:].lstrip()

        flags = self._identifier_re_flags()
        name_m = re.match(rf'^({self._VAR_BASE_PATTERN}[%$!#&]?)', text, flags=flags)
        if name_m:
            pos = name_m.end()
            # Optional array index / whole-array (): balanced scan, not greedy .*
            if pos < len(text) and text[pos] == '(':
                depth = 0
                j = pos
                in_str = False
                while j < len(text):
                    ch = text[j]
                    if ch == '"':
                        in_str = not in_str
                    elif not in_str:
                        if ch == '(':
                            depth += 1
                        elif ch == ')':
                            depth -= 1
                            if depth == 0:
                                j += 1
                                break
                    j += 1
                else:
                    j = pos  # unbalanced — leave as bare name
                lhs = text[:j].strip()
                rest = text[j:].lstrip()
            else:
                lhs = name_m.group(1)
                rest = text[name_m.end() :].lstrip()
            # Arithmetic first, then word bitwise (after complete LHS only).
            op_m = re.match(r'^([+\-*/]=)\s*(.+)$', rest, flags=re.DOTALL)
            if op_m:
                return _remember((lhs, op_m.group(1), op_m.group(2).strip()))
            bit_flags = re.DOTALL
            if not self._identifiers_case_sensitive():
                bit_flags |= re.IGNORECASE
            bit_m = re.match(
                r'^(OR|AND|EOR|XOR|DIV|MOD)\s*=\s*(.+)$',
                rest,
                flags=bit_flags,
            )
            if bit_m:
                op = bit_m.group(1).upper() + '='
                return _remember((lhs, op, bit_m.group(2).strip()))
            if rest.startswith('='):
                rhs = rest[1:].strip()
                self._validate_assignment_rhs(rhs)
                return _remember((lhs, '=', rhs))

        if '=' in text:
            var_part, expr = text.split('=', 1)
            rhs = expr.strip()
            self._validate_assignment_rhs(rhs)
            return _remember((var_part.strip(), '=', rhs))

        raise ValueError('assignment expected')

    def _program_display_lines(
        self,
        mode: str = 'standard',
        include_line_numbers: bool = True,
        start_line: Optional[int] = None,
        end_line: Optional[int] = None,
        case_fold: Optional[_SaveFold] = None,
    ) -> List[str]:
        goto_targets = self._collect_goto_targets()
        loop_depths = self._compute_loop_depths() if mode in ('pretty', 'refs') else {}
        def_header_lines: Set[int] = set()
        if mode == 'refs':
            def_header_lines, _, _ = self._collect_def_layout(sorted(self.program))
        lines: List[str] = []

        for line_num in sorted(self.program):
            if start_line is not None and line_num < start_line:
                continue
            if end_line is not None and line_num > end_line:
                continue
            raw_line = self.program[line_num]
            user_indent = self.line_indent.get(line_num, 0)
            show_number = True
            if mode == 'refs':
                show_number = line_num in goto_targets

            if mode in ('pretty', 'refs'):
                # Keep colon-joined statements on one listing line
                # (``A = C : B = D``, not a wrapped extra indent).
                from mini_basic.format.save_case import (
                    format_program_line as _fmt_line,
                    resolve_list_fold,
                )
                fold = resolve_list_fold(case_fold)
                formatted = _fmt_line(raw_line, fold) if raw_line.strip() else ''
                formatted = formatted.lstrip(' \t')
                indent_width = loop_depths.get(line_num, 0) * 4
            else:
                formatted = self.format_list_line(raw_line)
                indent_width = user_indent
            if not formatted:
                continue
            stmt_indent = ' ' * indent_width
            number = self._format_line_number(
                line_num,
                include_line_numbers and show_number,
                # Pad for LIST REFS column alignment; omit for SAVE PRETTY (no numbers).
                align=include_line_numbers,
            )
            if (
                mode == 'refs'
                and line_num in def_header_lines
                and lines
                and lines[-1] != ''
            ):
                lines.append('')
            lines.append(f'{number}{stmt_indent}{formatted}')
        return lines

    def _parse_unnumbered_line(self, line: str) -> Optional[Tuple[str, int]]:
        raw = line.rstrip('\n')
        if not raw.strip():
            return None
        match = re.match(r'^([ \t]*)(.+)$', raw)
        if not match:
            return None
        statement = match.group(2).rstrip()
        if not statement:
            return None
        return statement, self._indent_width(match.group(1))

    def _join_backslash_continuations(self, raw_lines) -> List[str]:
        """Join BBCSDL/C-style source lines continued with a trailing backslash.

        filters.txt style::

            lpf() = 0.07, 0.03, \\
            \\ 0.05, 0.06

        Also accepts a single trailing ``\\`` and a next line starting with ``\\``.
        """
        lines = list(raw_lines)
        if not lines:
            return lines
        out: List[str] = []
        i = 0
        while i < len(lines):
            # Preserve newline style of first segment when present.
            raw = lines[i]
            ends_nl = raw.endswith('\n') or raw.endswith('\r\n')
            s = raw.rstrip('\r\n')
            while True:
                stripped = s.rstrip()
                if not stripped.endswith('\\'):
                    break
                # Drop one trailing backslash (and spaces before it).
                s = stripped[:-1].rstrip()
                i += 1
                if i >= len(lines):
                    break
                nxt = lines[i].rstrip('\r\n').lstrip()
                if nxt.startswith('\\'):
                    nxt = nxt[1:].lstrip()
                s = f'{s} {nxt}' if s else nxt
            out.append(s + ('\n' if ends_nl else ''))
            i += 1
        return out

    def _parse_program_file(
        self,
        raw_lines,
    ) -> Optional[Tuple[List[Tuple[int, str, int]], bool]]:
        raw_lines = self._join_backslash_continuations(raw_lines)
        first_numbered_index: Optional[int] = None
        for index, line in enumerate(raw_lines):
            if self._parse_line_number(line):
                first_numbered_index = index
                break

        numbered: List[Tuple[int, str, int]] = []
        preamble: List[Tuple[str, int]] = []
        mixed_errors: List[Tuple[int, str]] = []

        for index, line in enumerate(raw_lines):
            parsed = self._parse_line_number(line)
            if parsed:
                numbered.append(parsed)
                continue
            parsed_unnumbered = self._parse_unnumbered_line(line)
            if not parsed_unnumbered:
                continue
            statement, indent = parsed_unnumbered
            if first_numbered_index is None or index < first_numbered_index:
                preamble.append((statement, indent))
                continue
            if indent > 0:
                try:
                    self._append_indented_continuation(numbered, statement, indent)
                except ValueError:
                    mixed_errors.append((index + 1, statement))
                continue
            mixed_errors.append((index + 1, statement))

        if mixed_errors:
            source_line, statement = mixed_errors[0]
            preview = self._preview_source_line(statement)
            print(
                f'? Mixed numbered and unnumbered lines at source line '
                f'{source_line}: {preview}',
            )
            print(
                '  (numbered programs may have unnumbered lines only before '
                'the first line number, or indented continuations)',
            )
            return None

        if numbered and preamble:
            # Keep comment preamble as separate lines (free numbers before first).
            # Only join *executable* preamble into line 0 (poem-style ON ERROR bootstrap).
            # Joining REM/' into one line 0 made LIST PRETTY smash headers and reformat
            # FG$/RESET$ as expressions (MB_COLOR.BAS).
            return self._merge_preamble_with_numbered(preamble, numbered), True

        if numbered:
            return numbered, True

        if not preamble:
            return [], False

        result: List[Tuple[int, str, int]] = []
        line_num = 10
        for statement, indent in preamble:
            result.append((line_num, statement, indent))
            line_num += 10
        return result, False

    @staticmethod
    def _is_comment_statement(statement: str) -> bool:
        s = statement.lstrip()
        if not s:
            return False
        if s.startswith("'"):
            return True
        return bool(re.match(r'^REM\b', s, re.IGNORECASE))

    def _merge_preamble_with_numbered(
        self,
        preamble: List[Tuple[str, int]],
        numbered: List[Tuple[int, str, int]],
    ) -> List[Tuple[int, str, int]]:
        """Attach leading unnumbered lines to free line numbers; bootstrap code on 0."""
        used = {n for n, _, _ in numbered}
        first = min(used) if used else 10
        free = [n for n in range(1, first) if n not in used]

        comments: List[Tuple[str, int]] = []
        code_parts: List[str] = []
        for stmt, indent in preamble:
            if self._is_comment_statement(stmt):
                comments.append((stmt, indent))
            else:
                code_parts.append(stmt)

        result: List[Tuple[int, str, int]] = []
        free_i = 0

        def _next_line_num() -> int:
            nonlocal free_i
            if free_i < len(free):
                n = free[free_i]
                free_i += 1
                return n
            # Prefer 0 once for overflow comments if still free, else after max used.
            if 0 not in used and all(r[0] != 0 for r in result):
                return 0
            n = max(used | {r[0] for r in result}, default=0) + 1
            while n in used or any(r[0] == n for r in result):
                n += 1
            return n

        for stmt, indent in comments:
            ln = _next_line_num()
            result.append((ln, stmt, indent))
            used.add(ln)

        if code_parts:
            bootstrap = ': '.join(code_parts)
            if 0 not in used:
                result.append((0, bootstrap, 0))
            else:
                ln = _next_line_num()
                result.append((ln, bootstrap, 0))

        result.extend(numbered)
        result.sort(key=lambda item: item[0])
        return result

    def _parse_auto_line(self, default_num: int, text: str) -> Tuple[int, str]:
        raw = text.rstrip('\n')
        numbered = re.match(r'^[ \t]*(\d+)(.*)$', raw)
        if numbered:
            return int(numbered.group(1)), numbered.group(2)
        return default_num, raw

    def _choose_external_editor(self) -> Optional[List[str]]:
        """VISUAL / EDITOR, then notepad (Windows) or nano/vim/vi."""
        import shutil

        configured = (os.environ.get('VISUAL') or os.environ.get('EDITOR') or '').strip()
        if configured:
            import shlex

            posix = os.name != 'nt'
            try:
                cmd = shlex.split(configured, posix=posix)
            except ValueError:
                cmd = [configured]
            if cmd:
                resolved = shutil.which(cmd[0])
                if resolved:
                    return [resolved, *cmd[1:]]
                if os.path.isfile(cmd[0]):
                    return cmd
                return None

        if sys.platform == 'win32':
            notepad = shutil.which('notepad') or shutil.which('notepad.exe')
            if notepad:
                return [notepad]
            return None

        for name in ('nano', 'vim', 'vi', 'sensible-editor', 'editor'):
            found = shutil.which(name)
            if found:
                return [found]
        return None

    def _launch_external_editor(self, path: str) -> bool:
        """Open *path* in the system editor and wait. False if it could not start."""
        import subprocess

        cmd = self._choose_external_editor()
        if not cmd:
            print('? no editor (set EDITOR or VISUAL)')
            print('  EDIT n     edit one line (prefilled; arrows move in the text)')
            return False
        try:
            status = subprocess.call([*cmd, path])
        except OSError as exc:
            print(f'? cannot start editor: {exc}')
            return False
        return status == 0 or os.path.isfile(path)

    def _write_program_for_edit(self, path: str) -> str:
        """Dump current memory for an external editor (does not change SAVE name)."""
        case_fold = self._detokenize_fold()
        if self._program_source_numbered is False:
            lines = self._program_display_lines(
                'pretty',
                include_line_numbers=False,
                case_fold=case_fold,
            )
        else:
            lines = []
            for num in sorted(self.program):
                indent = ' ' * self.line_indent.get(num, 0)
                lines.append(
                    f'{self._format_line_number(num, True)}'
                    f'{indent}{self.format_list_line(self.program[num])}'
                )
        text = ''.join(f'{line}\n' for line in lines)
        with open(path, 'w', encoding='utf-8', newline='\n') as handle:
            handle.write(text)
        return text

    def _program_edit_snapshot(self) -> Tuple[Tuple[int, int, str], ...]:
        return tuple(
            (num, self.line_indent.get(num, 0), self.program[num])
            for num in sorted(self.program)
        )

    @staticmethod
    def _normalize_edit_text(text: str) -> str:
        return text.replace('\r\n', '\n').replace('\r', '\n')

    @staticmethod
    def _decode_edit_file_bytes(data: bytes) -> str:
        """Notepad may rewrite the temp file as UTF-8 BOM or UTF-16."""
        if data.startswith(b'\xff\xfe') or data.startswith(b'\xfe\xff'):
            return data.decode('utf-16')
        if data.startswith(b'\xef\xbb\xbf'):
            return data[3:].decode('utf-8')
        try:
            return data.decode('utf-8')
        except UnicodeDecodeError:
            return data.decode('utf-16')

    def _read_edit_file_text(self, path: str) -> Optional[str]:
        try:
            with open(path, 'rb') as handle:
                data = handle.read()
        except OSError as exc:
            self._emit_error(f'? EDIT: cannot read editor file ({exc})')
            return None
        try:
            return self._decode_edit_file_bytes(data)
        except UnicodeDecodeError as exc:
            self._emit_error(f'? EDIT: editor file is not readable text ({exc})')
            return None

    def _apply_edited_source(self, text: str) -> bool:
        """Replace memory from editor text. False leaves the previous program."""
        from ..dialect_hint import split_dialect_hints

        saved_name = self.loaded_filename
        if not text.strip():
            self.new(announce=False, clear_loaded_filename=False)
            self.loaded_filename = saved_name
            print('Program cleared.')
            return True

        raw_lines = text.splitlines(keepends=True)
        raw_lines, hint = split_dialect_hints(raw_lines)
        if hint is not None:
            self._apply_dialect_hint(hint, announce=False)
        parsed = self._parse_program_file(raw_lines)
        if parsed is None:
            self._emit_error('? EDIT: could not parse editor text (program unchanged)')
            return False
        parsed_lines, source_was_numbered = parsed
        if not parsed_lines:
            self.new(announce=False, clear_loaded_filename=False)
            self.loaded_filename = saved_name
            print('Program cleared.')
            return True
        if not self._validate_program_dialect(
            parsed_lines, source_was_numbered, announce=False,
        ):
            self._emit_error('? EDIT: dialect check failed (program unchanged)')
            return False

        self.new(announce=False, clear_loaded_filename=False)
        self._program_source_numbered = source_was_numbered
        for line_num, statement, indent in parsed_lines:
            self.set_program_line(line_num, statement, indent)
        self.loaded_filename = saved_name
        count = len(self.program)
        noun = 'line' if count == 1 else 'lines'
        print(f'Reloaded {count} {noun} from editor.')
        if saved_name:
            self._sync_display_caption(os.path.basename(saved_name))
        return True

    def _real_program_file(self) -> Optional[str]:
        """LOAD/SAVE path, or None when the session only exists in memory/tmp."""
        name = (self.loaded_filename or '').strip()
        if not name:
            return None
        base = os.path.basename(name)
        if base.startswith('mb_edit_') and base.lower().endswith('.bas'):
            return None
        return name

    def _prompt_save_after_edit(self) -> None:
        """Ask before writing the real file; EDIT itself only touched a temp."""
        real = self._real_program_file()
        try:
            if real:
                answer = input(f'Save changes to {real}? (Y/N) ').strip()
            else:
                answer = input(
                    'Save as (filename, or Enter to keep in memory only): '
                ).strip()
        except (KeyboardInterrupt, EOFError):
            print()
            print('Kept in memory only. SAVE writes the file later.')
            return
        if real:
            if answer.lower() in ('y', 'yes'):
                self.save(real)
            else:
                print('Kept in memory only. SAVE writes the file later.')
            return
        if answer:
            self.save(answer)
        else:
            print('Kept in memory only.')

    def edit_program(self):
        """Bare EDIT: open the current program in the system text editor, then reload.

        Writes a temp ``.bas``, waits for the editor, then replaces memory from
        that file. If the program came from a real LOAD/SAVE name, ask before
        writing that file. If there is no real file, offer Save as.
        """
        import tempfile

        fd, path = tempfile.mkstemp(prefix='mb_edit_', suffix='.bas')
        os.close(fd)
        try:
            written = self._write_program_for_edit(path)
            if not self._launch_external_editor(path):
                return
            if not os.path.isfile(path):
                self._emit_error('? EDIT: editor file disappeared (program unchanged)')
                return
            text = self._read_edit_file_text(path)
            if text is None:
                return
            if self._normalize_edit_text(text) == self._normalize_edit_text(written):
                print('No changes.')
                return
            if not self._apply_edited_source(text):
                return
            self._prompt_save_after_edit()
        finally:
            try:
                os.remove(path)
            except OSError:
                pass

