    def _bbc_bare_numeric_func_arg(
        self,
        expr: str,
        func_end: int,
        func: str,
    ) -> Optional[Tuple[Optional[str], int]]:
        pos = func_end
        while pos < len(expr) and expr[pos].isspace():
            pos += 1
        if pos < len(expr) and expr[pos] == '(':
            return None
        if func in self._BBC_BARE_NO_ARG_FUNCS:
            return None, pos
        # Glued string-func call as arg: VALMID$(s,i) / LENLEFT$(s,n) etc.
        str_func = re.match(
            r'^(MID\$|LEFT\$|RIGHT\$|CHR\$|STR\$|INKEY\$|STRING\$)\s*\(',
            expr[pos:],
            re.IGNORECASE,
        )
        if str_func:
            paren_start = pos + str_func.end() - 1
            paren_end = self._match_paren(expr, paren_start)
            if paren_end is not None and paren_end >= 0:
                arg = expr[pos : paren_end + 1]
                return arg, paren_end + 1
        if func in self._BBC_BARE_STRING_ARG_FUNCS:
            # Also accept quoted string literals: VAL"12"
            if pos < len(expr) and expr[pos] == '"':
                end = pos + 1
                while end < len(expr):
                    if expr[end] == '"':
                        end += 1
                        break
                    end += 1
                return expr[pos:end], end
            var_match = re.match(
                rf'^({self._VAR_BASE_PATTERN})([%$!#]?)',
                expr[pos:],
                self._identifier_re_flags(),
            )
            if not var_match:
                return None
            arg = var_match.group(1) + var_match.group(2)
            return arg, pos + var_match.end()
        if func == 'RND':
            num_match = re.match(r'^(-?\d+\.?\d*)', expr[pos:])
            if num_match:
                return num_match.group(1), pos + num_match.end()
            return None, pos
        # Nested glued numeric builtin: SINRADT → SINRAD + T, or RADT after SIN.
        nested = re.match(
            rf'({_NUMERIC_BUILTIN_FUNC_RE})',
            expr[pos:],
            re.IGNORECASE,
        )
        if nested:
            nfunc = nested.group(1).upper()
            n_end = pos + nested.end()
            inner = self._bbc_bare_numeric_func_arg(expr, n_end, nfunc)
            if inner is not None:
                iarg, iend = inner
                nested_val = self._eval_numeric_builtin_call(nfunc, iarg)
                return self._embed_numeric_for_eval(nested_val), iend
        var_match = re.match(
            rf'^({self._VAR_BASE_PATTERN})([%$!#]?)',
            expr[pos:],
            self._identifier_re_flags(),
        )
        if var_match:
            arg = var_match.group(1) + var_match.group(2)
            return arg, pos + var_match.end()
        num_match = re.match(r'^(-?\d+\.?\d*)', expr[pos:])
        if num_match:
            return num_match.group(1), pos + num_match.end()
        return None

    def _bbc_to_uint32(self, value: float) -> int:
        return int(value) & 0xFFFFFFFF

    def _bbc_hex_string(self, value: object) -> str:
        """Return uppercase hex digits (no 0x) for STR$~ / HEX$ / PRINT ~.

        Non-negative (incl. bigints): full hex. Negative: 32-bit two's complement.
        """
        try:
            ival = int(value)
        except (TypeError, ValueError):
            ival = int(float(value))
        if ival >= 0:
            return f'{ival:X}'
        else:
            uval = self._bbc_to_uint32(float(ival))
            return f'{uval:X}'

    def _bbc_bin_string(self, value: object) -> str:
        """Uppercase-free binary digits (no & or prefix) for BIN$.

        Non-negative (incl. bigints): full bits. Negative: 32-bit two's complement.
        """
        try:
            ival = int(value)
        except (TypeError, ValueError):
            ival = int(float(value))
        if ival >= 0:
            return format(ival, 'b')
        return format(self._bbc_to_uint32(float(ival)), 'b')

    def _pad_base_digits(self, digits: str, width: object) -> str:
        """HEX$(n, w) / BIN$(n, w): left-pad with 0; never truncate."""
        try:
            w = int(width)
        except (TypeError, ValueError):
            w = int(float(width))
        if w <= 0 or len(digits) >= w:
            return digits
        return digits.zfill(w)

    def _bbc_from_uint32(self, bits: int) -> float:
        if bits >= 0x80000000:
            bits -= 0x100000000
        return float(bits)

    def _bbc_bitwise_not(self, value: float) -> float:
        return self._bbc_from_uint32((~self._bbc_to_uint32(value)) & 0xFFFFFFFF)

    def _bbc_bitwise_xor(self, left: float, right: float) -> float:
        return self._bbc_from_uint32(
            self._bbc_to_uint32(left) ^ self._bbc_to_uint32(right),
        )

    def _bbc_bitwise_eqv(self, left: float, right: float) -> float:
        return self._bbc_from_uint32(
            (~(self._bbc_to_uint32(left) ^ self._bbc_to_uint32(right))) & 0xFFFFFFFF,
        )

    def _bbc_bitwise_imp(self, left: float, right: float) -> float:
        return self._bbc_from_uint32(
            ((~self._bbc_to_uint32(left)) & 0xFFFFFFFF) | self._bbc_to_uint32(right),
        )

    def _print_atom(self, expr: str) -> str:
        expr = expr.strip()
        if re.fullmatch(r'[-+]?(?:INF|INFINITY)', expr, re.IGNORECASE):
            return '-INF' if expr.startswith('-') else 'INF'
        if re.fullmatch(r'[-+]?\d+', expr):
            return expr
        # String variables / $ expressions must not go through arith (A$ is not Python).
        if '$' in expr or self._fragment_is_string_expr(expr):
            try:
                return self._eval_string_expr(expr)
            except Exception:
                pass
        if not self._RE_FN_CALL.search(expr) and '$' not in expr:
            try:
                reduced = self._eval_whole_arith(expr)
            except Exception:
                reduced = None
            if isinstance(reduced, int) and not isinstance(reduced, bool):
                return str(reduced)
            if isinstance(reduced, float):
                return self._format_number(reduced)
        try:
            if expr.upper() == '@%':
                return self._format_number(float(self.bbc_at_percent))
            system_name = self._canonical_system_var_name(expr)
        except ValueError:
            system_name = None
        if system_name:
            return self._format_number(self._get_system_var(system_name))
        # BBCSDL: a%% (64-bit / bigint storage) before a% (32-bit-style key).
        # Always format via _format_stored_int so we print full decimal digits,
        # never float scientific (SDL-style 1.222222E11 looks like a bug when
        # we already hold Python int / bigint behind %).
        id_flags = self._identifier_re_flags()
        int64_match = re.match(
            rf'^({self._VAR_BASE_PATTERN})%%$',
            expr,
            flags=id_flags,
        )
        if int64_match:
            key = self._normalize_identifier(int64_match.group(1)) + '%%'
            return self._format_stored_int(self.int_variables.get(key, 0))
        int_match = re.match(
            rf'^({self._VAR_BASE_PATTERN})%$',
            expr,
            flags=id_flags,
        )
        if int_match:
            return self._format_stored_int(
                self.int_variables.get(
                    self._normalize_identifier(int_match.group(1)),
                    0,
                )
            )
        # BBC # (double) / ! (single): always format as floating-point, never
        # expand float64 via int() into a long false-precision decimal
        # (e.g. a#=FNfact(100) → 9.3326…E157, not a 158-digit integer).
        float_suf_match = re.match(
            rf'^({self._VAR_BASE_PATTERN})[#!]$',
            expr,
            flags=id_flags,
        )
        if float_suf_match:
            base = self._normalize_identifier(float_suf_match.group(1))
            return self._format_number(float(self.variables.get(base, 0.0)))
        bare_match = re.match(
            rf'^({self._VAR_BASE_PATTERN})$',
            expr,
            flags=self._identifier_re_flags(),
        )
        if bare_match:
            base = self._normalize_identifier(bare_match.group(1))
            letter = base[0].upper() if base else ''
            if base in self.int_variables or self.default_var_types.get(letter) == 'int':
                return self._format_stored_int(self.int_variables.get(base, 0))
            if base in self.str_variables or self.default_var_types.get(letter) == 'str':
                return self.str_variables.get(base, '')
            if base in self.variables:
                return self._format_number(float(self.variables[base]))
        str_match = re.match(
            rf'^({self._VAR_BASE_PATTERN})\$$',
            expr,
            flags=self._identifier_re_flags(),
        )
        if str_match:
            return self.str_variables.get(
                self._normalize_identifier(str_match.group(1)),
                '',
            )
        # BBCSDL struct member access in print/eval context: obj.foo%  obj.bar$  obj.baz
        if '.' in expr:
            # try direct key lookup in struct_members (keys carry suffix like obj.bar$)
            if expr in self.struct_members:
                v = self.struct_members[expr]
                if isinstance(v, str):
                    return v
                if isinstance(v, (int, float)) and (expr.endswith('%') or expr.endswith('%%')):
                    return self._format_stored_int(v)
                if isinstance(v, (int, float)):
                    return self._format_number(float(v))
                return str(v)
            # also support without explicit suf on lookup for bare dotted
            dkey = expr
            if dkey in self.struct_members:
                v = self.struct_members[dkey]
                return str(v) if isinstance(v, str) else (self._format_stored_int(v) if isinstance(v, int) else self._format_number(float(v)))
        parsed = self._parse_array_lvalue(expr)
        if parsed is not None:
            base, kind, indices_expr = parsed
            value = self._array_get(base, kind, self._eval_array_indices(indices_expr))
            if kind == 'str':
                return str(value)
            if kind == 'int':
                return self._format_stored_int(value)
            return self._format_number(float(value))
        if expr.startswith('"'):
            return self._decode_bbc_adjacent_string_literals(expr)
        return self._format_number(self._eval_numeric(expr))

    def _present_terminal_display(self) -> None:
        """Flush terminal display so TAB/PRINT updates are visible mid-loop.

        Streaming mode already writes through to stdout on each PRINT; only
        grid mode (after goto) needs a full present() repaint.
        """
        if (
            self._display is not None
            and hasattr(self._display, 'present')
            and self._display_backend_name() == 'terminal'
        ):
            if not getattr(self._display, '_positioned', False):
                # Still flush any held incomplete CSI + tail via present().
                try:
                    self._display.present()
                except Exception:
                    pass
                return
            try:
                self._display.present()
            except Exception:
                pass

    def _inkey_from_pygame(self) -> str:
        """Non-blocking key from pygame display, if active."""
        if not self._display_enabled():
            return ''
        if hasattr(self._display, 'pump_events'):
            try:
                self._display.pump_events()
            except Exception:
                pass
        pygame_mod = getattr(self._display, '_pygame', None)
        if pygame_mod is None or not pygame_mod.get_init():
            return ''
        try:
            pygame_mod.event.pump()
            for event in pygame_mod.event.get():
                if event.type != pygame_mod.KEYDOWN:
                    continue
                if event.key == pygame_mod.K_ESCAPE:
                    return '\x1b'
                try:
                    from ..display import pygame_keydown_char
                    ch = pygame_keydown_char(pygame_mod, event)
                except Exception:
                    ch = None
                if ch:
                    return ch
                if getattr(event, 'unicode', None):
                    return str(event.unicode)
        except Exception:
            return ''
        return ''

    def _inkey_value(self) -> str:
        # Prefer pygame when a graphical display owns the keyboard.
        pg = self._inkey_from_pygame()
        if pg:
            return pg
        if sys.platform == 'win32':
            try:
                import msvcrt
                if msvcrt.kbhit():
                    char = msvcrt.getch()
                    # Swallow DOS extended prefixes (arrows etc.) so they are not
                    # mistaken for printable keys in INKEY$ loops.
                    if char in (b'\x00', b'\xe0'):
                        if msvcrt.kbhit():
                            msvcrt.getch()
                        return ''
                    if isinstance(char, bytes):
                        return char.decode('latin-1', errors='ignore')
                    return char
                return ''
            except ImportError:
                return ''
        import select
        if not sys.stdin.isatty():
            return ''
        try:
            readable, _, _ = select.select([sys.stdin], [], [], 0)
            if readable:
                return sys.stdin.read(1)
            return ''
        except OSError:
            return ''

    def _drain_inkey_buffer(self) -> None:
        """Discard pending console/pygame key events.

        Windows keyboard autorepeat fills the console buffer so a held key makes
        every subsequent INKEY$(n) return in 0ms and a REPEAT loop finishes in
        one flash (user only sees the last TAB frame, e.g. ``x*19``).  Timed
        INKEY$(n) for n>0 clears stale input first, then waits for a *new*
        press (or timeout) — closer to usable BBC game-loop pacing on PCs.
        """
        for _ in range(256):
            if not self._inkey_value():
                break

    def _inkey_code(self) -> float:
        text = self._inkey_value()
        return float(ord(text[0])) if text else -1.0

    def _inkey_bbc_negative_scan(self, scan_code: int) -> float:
        """BBC INKEY(n) for n < 0: immediate keyboard scan (non-blocking)."""
        if self._display_enabled():
            if hasattr(self._display, 'pump_events'):
                self._display.pump_events()
            pygame_mod = getattr(self._display, '_pygame', None)
            if pygame_mod is not None and pygame_mod.get_init():
                pygame_mod.event.pump()
                pressed = pygame_mod.key.get_pressed()
                if pressed[pygame_mod.K_ESCAPE]:
                    return 27.0
                for key_code in range(32, 127):
                    if pressed[key_code]:
                        return float(key_code)
        text = self._inkey_value()
        if text:
            return float(ord(text[0]))
        return -1.0

    def _inkey_code_wait(self, timeout_cs: float) -> float:
        if timeout_cs < 0:
            return self._inkey_bbc_negative_scan(int(timeout_cs))
        # Make prior PRINT/TAB/PLOT visible before waiting (same-line REPEAT:PRINT:INKEY
        # loops; welcome PROCPLOT ends with D%=INKEY2 as a frame delay so invert zaps
        # are seen — terminal present alone is a no-op for pygame).
        self._flush_program_output()
        self._present_terminal_display()
        if timeout_cs > 0 and self._display_enabled():
            # Force: rate-limited flush was dropping every invert frame of the swoosh
            # (draw+erase finish inside one interval → only the final erase shows).
            self._flush_display(force=True)
        if timeout_cs == 0:
            # INKEY$(0) / INKEY(0): non-blocking poll.
            # Official Acorn docs call n=0 an indefinite wait, but classic game
            # listings (including RACE.BBC's K$=INKEY$(0) frame poll) treat 0 as
            # "return immediately with empty/-1 if no key". Use GET / GET$ /
            # INKEY$(-1) style waits only via GET$/GET for blocking input.
            if self._display_enabled() and not self._display.poll():
                self._invoke_on_close_and_exit()
            text = self._inkey_value()
            if text:
                return float(ord(text[0]))
            return -1.0

        # Positive timeout: wait up to n centiseconds for a key.
        # Windows autorepeat would otherwise make REPEAT:A$=INKEY$(10):… finish
        # hundreds of iterations in one flash (user only sees final TAB frame).
        # For short frame-style timeouts (n <= 50 cs) we:
        #   - return the first key seen
        #   - drain same-character autorepeat
        #   - still wait out the rest of the interval (stable frame pacing)
        # Longer timeouts return as soon as a key arrives (prompt-style).
        deadline = time.perf_counter() + (timeout_cs / 100.0)
        pad_frame = timeout_cs <= 50.0
        found: Optional[float] = None
        while True:
            if self._display_enabled() and not self._display.poll():
                self._invoke_on_close_and_exit()
            if found is None:
                text = self._inkey_value()
                if text:
                    found = float(ord(text[0]))
                    # Drop a burst of same-character autorepeat (bounded).
                    for _ in range(64):
                        more = self._inkey_value()
                        if not more or more != text:
                            break
                    if not pad_frame:
                        return found
            if time.perf_counter() >= deadline:
                return found if found is not None else -1.0
            # While padding the frame, discard a small burst of held-key noise.
            if found is not None:
                for _ in range(16):
                    if not self._inkey_value():
                        break
            time.sleep(0.01)

