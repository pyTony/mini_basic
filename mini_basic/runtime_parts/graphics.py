    def pump_display_idle(self) -> bool:
        """Keep the pygame window alive while the REPL waits for input.

        Returns True to keep the REPL running. Window close tears down surfaces
        but does **not** exit the REPL — next RUN/MODE reopens the window.
        """
        if self._display is None or self._program_stdout is not None:
            return True
        if not self._display_live and not self._display_is_alive():
            return True
        # Streaming terminal: no window to pump; avoid empty full-grid present().
        if (
            self._display_backend_name() == 'terminal'
            and not getattr(self._display, '_positioned', False)
        ):
            return True
        if not self._display_is_alive():
            self._mark_display_closed()
            return True
        try:
            if hasattr(self._display, 'pump_events'):
                self._display.pump_events()
            self._display.present()
            if not self._display.poll():
                self._mark_display_closed()
        except Exception:
            self._mark_display_closed()
        return True

    def _ensure_display(self) -> None:
        if self._program_stdout is not None:
            return
        backend = (self.config.display or 'terminal').strip().lower()
        if backend in ('none', 'null'):
            return
        # REPL already has TerminalDisplay; CLI never did. After auto-enable
        # pygame, drop the console backend or MODE/COLOUR paint the terminal
        # (soccerball COLOUR 130 → green text screen) and CIRCLE/PLOT are no-ops.
        if backend == 'pygame' and self._display is not None:
            if type(self._display).__name__ != 'PygameDisplay':
                try:
                    self._display.end_run()
                except Exception:
                    pass
                self._display = None
                self._display_live = False
        if backend in ('', 'terminal'):
            # Create a real TerminalDisplay (grid + batched ANSI present)
            # so that high-volume TAB/PRINT programs are fast in terminal mode.
            if self._display is None:
                from mini_basic.display import create_display
                self._display = create_display(
                    'terminal',
                    text_cols=self.config.display_cols,
                    text_rows=self.config.display_rows,
                )
            if not self._display_live or not self._display_is_alive():
                self._display.begin_run()
                self._display_live = True
            return
        if self._display is None:
            from mini_basic.display import create_display, pygame_install_hint

            try:
                self._display = create_display(
                    backend,
                    text_cols=self.config.display_cols,
                    text_rows=self.config.display_rows,
                    graphics_width=self.config.graphics_width,
                    graphics_height=self.config.graphics_height,
                    scale=self.config.display_scale,
                    scale_locked=self.config.display_scale_locked,
                    caption=self.config.display_caption,
                    fps_limit=self.config.display_fps_limit,
                )
            except ImportError as exc:
                # Auto-enabled pygame without package installed, or locked request.
                if self.config.display_locked or backend != 'pygame':
                    raise ImportError(pygame_install_hint()) from exc
                print(
                    'pygame missing — falling back to terminal display.\n'
                    + pygame_install_hint()
                )
                self.config.display = 'terminal'
                self._display = create_display(
                    'terminal',
                    text_cols=self.config.display_cols,
                    text_rows=self.config.display_rows,
                )
                backend = 'terminal'
        if hasattr(self._display, 'fps_limit'):
            self._display.fps_limit = max(0, int(self.config.display_fps_limit))
        # Reopen after user closed the window (or first open).
        if self._display is not None:
            setattr(self._display, '_refresh_enabled', self._refresh_enabled)
        if not self._display_live or not self._display_is_alive():
            if self._display is not None:
                setattr(self._display, '_refresh_enabled', self._refresh_enabled)
            try:
                self._display.begin_run()
            except Exception:
                # Surface zombie: force full teardown and recreate once.
                try:
                    self._display.end_run()
                except Exception:
                    pass
                from mini_basic.display import create_display, ensure_no_pygame_leftovers
                ensure_no_pygame_leftovers()
                try:
                    self._display = create_display(
                        backend,
                        text_cols=self.config.display_cols,
                        text_rows=self.config.display_rows,
                        graphics_width=self.config.graphics_width,
                        graphics_height=self.config.graphics_height,
                        scale=self.config.display_scale,
                        scale_locked=self.config.display_scale_locked,
                        caption=self.config.display_caption,
                        fps_limit=self.config.display_fps_limit,
                    )
                except ImportError:
                    self.config.display = 'terminal'
                    self._display = create_display(
                        'terminal',
                        text_cols=self.config.display_cols,
                        text_rows=self.config.display_rows,
                    )
                self._display.begin_run()
            self._display_live = True
            if self._graphics_mode and hasattr(self._display, 'set_mode'):
                self._apply_bbc_mode(self._graphics_mode)
                self._display.set_mode(self._graphics_mode)

