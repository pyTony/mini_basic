    def _enable_pygame_display(self, *, announce: bool = True) -> None:
        if self.config.display_locked:
            return
        if self._display_backend_name() != 'terminal':
            return
        from mini_basic.util.session import session_supports_gui

        if not session_supports_gui():
            if announce:
                print(
                    'Graphics skipped (text-only session; '
                    'use --display pygame if a window is available, '
                    'or unset MINIBASIC_NO_GRAPHICS / set DISPLAY)'
                )
            return
        from mini_basic.display import pygame_available, pygame_install_hint

        if not pygame_available():
            if announce:
                print(
                    'Graphics detected, but pygame is not installed — using terminal.\n'
                    + pygame_install_hint()
                )
            return
        self.config.display = 'pygame'
        self.config.hold_display_open = True
        _apply_pygame_display_defaults(self.config)
        if self.loaded_filename:
            self._sync_display_caption(os.path.basename(self.loaded_filename))
        if announce:
            print(
                'Graphics detected; pygame display enabled '
                '(use --display terminal to force text mode)'
            )

